-- StudentSend schema for Supabase (PostgreSQL).
-- Run in a new Supabase project's SQL Editor as postgres.
-- Teacher accounts are managed by Supabase Auth; add approved auth user IDs to app_users.

create type public.staff_role as enum ('admin', 'teacher');
create type public.student_status as enum ('active', 'inactive');
create type public.assignment_status as enum ('active', 'inactive');
create type public.submission_status as enum ('pending', 'submitted', 'checking', 'checked', 'returned', 'late');

create table public.app_users (
    user_id uuid primary key references auth.users(id) on delete cascade,
    display_name text not null,
    role public.staff_role not null default 'teacher',
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table public.courses (
    id bigint generated by default as identity primary key,
    course_code varchar(50),
    course_name varchar(255) not null,
    class_name varchar(100) not null default '',
    created_at timestamptz not null default now(),
    constraint courses_name_class_unique unique (course_name, class_name),
    constraint courses_code_class_unique unique (course_code, class_name)
);
